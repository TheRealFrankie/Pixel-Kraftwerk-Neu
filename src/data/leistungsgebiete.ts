/**
 * Nachbarstädte für Interlinking auf Regionsseiten.
 * Die Städteliste ist grob nach Entfernung von Groitzsch sortiert; Städte mit
 * gleichem subtitle (Region/Bundesland) werden bevorzugt, danach wird mit
 * Listen-Nachbarn aufgefüllt.
 */
export function getNeighborCities(slug: LeistungsgebietSlug, count = 6): LeistungsgebietCity[] {
  const index = LEISTUNGSGEBIETE_CITIES.findIndex((c) => c.slug === slug);
  if (index === -1) return [];
  const self = LEISTUNGSGEBIETE_CITIES[index];

  const candidates = LEISTUNGSGEBIETE_CITIES.map((city, i) => ({
    city,
    distance: Math.abs(i - index),
    sameRegion: city.subtitle === self.subtitle && city.subtitle !== 'Hauptsitz',
  })).filter((c) => c.city.slug !== slug);

  candidates.sort((a, b) => {
    if (a.sameRegion !== b.sameRegion) return a.sameRegion ? -1 : 1;
    return a.distance - b.distance;
  });

  return candidates.slice(0, count).map((c) => c.city as LeistungsgebietCity);
}

